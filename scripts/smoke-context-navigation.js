const path=require('path');
const store=new Map();
global.localStorage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k),clear:()=>store.clear()};
global.window={location:{search:'?companyId=CMP-002'}};
require(path.resolve(__dirname,'../js/core/admin-state.js'));
const api=window.VoltDriveAdmin,state=api.getState();
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
assert(api.companyContextId()==='CMP-002','Platform Admin should resolve requested company context.');
assert(api.companyContext()?.name==='Ararat Mobility','Company context should resolve the actual company entity.');
assert(api.companyContextMatch('CMP-002')===true&&api.companyContextMatch('CMP-001')===false,'Company context must narrow company-aware data.');
assert(api.countryContextMatch('AM')===true&&api.countryContextMatch('GE')===false,'Company context must also narrow market-aware data to the company country.');
assert(api.itemMatchesCompanyContext({companyId:'CMP-002'})===true,'Company-scoped item should match context.');
assert(api.itemMatchesCompanyContext({companyId:'CMP-001'})===false,'Other-company item must not match context.');
assert(api.contextUrl('payments.html','CMP-002')==='payments.html?companyId=CMP-002','Context URL must preserve company id.');
window.location.search='?countryCode=GE';
assert(api.companyContextId()==='','Market context must not invent a company.');
assert(api.countryContextCode()==='GE','Market context should resolve a permitted country.');
assert(api.countryContextMatch('GE')===true&&api.countryContextMatch('AM')===false,'Market context must narrow country-aware data.');
assert(api.countryContextUrl('tariffs.html','GE')==='tariffs.html?countryCode=GE','Market URL must preserve country code.');
api.setCurrentUser('USR-009');
window.location.search='?companyId=CMP-001';
assert(api.companyContextId()==='','Company Admin must not activate context for another company via URL.');
window.location.search='?companyId=CMP-002';
assert(api.companyContextId()==='CMP-002','Company Admin should retain own-company context.');
console.log('OK: contextual navigation scope helpers passed.');
